/**
 * Public site URL used for canonical links, Open Graph, sitemap and robots.
 * 1. NEXT_PUBLIC_SITE_URL, once a custom domain is set.
 * 2. Otherwise Vercel's production URL (a system variable available at build time).
 * 3. Otherwise localhost, for local development.
 */
function resolveSiteUrl(): string {
  const explicit = process.env.NEXT_PUBLIC_SITE_URL;
  if (explicit) return explicit;
  const vercelHost = process.env.VERCEL_PROJECT_PRODUCTION_URL ?? process.env.VERCEL_URL;
  if (vercelHost) return `https://${vercelHost}`;
  return "http://localhost:3000";
}

export const siteUrl = resolveSiteUrl().replace(/\/$/, "");

